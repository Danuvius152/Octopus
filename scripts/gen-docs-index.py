#!/usr/bin/env python3
"""Generate current-contract and unfinished-plan indexes in docs/catalog.md.

Each document declares `> **Status:** <status> — <summary>` below its title.
The directory constrains the status; `--check` detects index drift without
writing. scripts/check.sh uses that mode as its documentation gate.
"""

from __future__ import annotations

import re
import sys
from itertools import pairwise
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "docs" / "catalog.md"
STATUSES = {
    "implemented": {"implemented"},
    "plans": {"proposed", "in-progress", "paused"},
}

_STATUS_RE = re.compile(r"^> \*\*Status:\*\* (?P<status>[^—]+)—(?P<summary>.+)$")

# Active work precedes proposed and paused work; contracts sort by title.
_ORDER = {"in-progress": 0, "proposed": 1, "paused": 2, "implemented": 0}


def read_entries(folder: str) -> list[tuple[str, str, str, str]]:
    """`(filename, title, status, summary)` for every document, in table order."""
    rows: list[tuple[str, str, str, str]] = []
    missing: list[str] = []
    directory = ROOT / "docs" / folder
    if not directory.is_dir():
        raise SystemExit(f"missing documentation directory: {directory}")
    for path in sorted(directory.glob("*.md")):
        lines = path.read_text().split("\n")
        title = lines[0].removeprefix("# ").strip() if lines[0].startswith("# ") else ""
        status = summary = ""
        for line in lines[1:8]:
            m = _STATUS_RE.match(line.strip())
            if m:
                status = m.group("status").strip()
                summary = m.group("summary").strip()
                break
        if not (title and status and summary):
            missing.append(path.name)
            continue
        if status not in STATUSES[folder]:
            raise SystemExit(f"docs/{folder}/{path.name}: invalid status {status!r}")
        rows.append((path.name, title, status, summary))
    if missing:
        raise SystemExit(
            f"these docs/{folder} files have no `> **Status:** <status> — <summary>` line under "
            "their title:\n  " + "\n  ".join(missing)
        )
    rows.sort(key=lambda r: (_ORDER[r[2]], r[1].lower()))
    return rows


def markers(folder: str) -> tuple[str, str]:
    return (
        f"<!-- BEGIN {folder}-index (generated by scripts/gen-docs-index.py) -->",
        f"<!-- END {folder}-index -->",
    )


def render(folder: str, rows: list[tuple[str, str, str, str]]) -> str:
    begin, end = markers(folder)
    label = "当前合同" if folder == "implemented" else "未完成计划"
    out = [begin, "", f"| {label} | 状态 | 范围 |", "|---|---|---|"]
    for name, title, status, summary in rows:
        out.append(f"| [{title}]({folder}/{name}) | {status} | {summary} |")
    out += ["", end]
    return "\n".join(out)


def replace_indexes(catalog: str) -> str:
    blocks: list[tuple[int, int, str]] = []
    for folder in STATUSES:
        begin_marker, end_marker = markers(folder)
        start, end = catalog.find(begin_marker), catalog.find(end_marker)
        if catalog.count(begin_marker) != 1 or catalog.count(end_marker) != 1 or start >= end:
            raise SystemExit(
                f"docs/catalog.md needs exactly one ordered {begin_marker} / {end_marker} pair"
            )
        blocks.append((start, end + len(end_marker), render(folder, read_entries(folder))))
    blocks.sort()
    if any(left[1] > right[0] for left, right in pairwise(blocks)):
        raise SystemExit("docs/catalog.md index marker regions must not overlap")
    for start, end, block in reversed(blocks):
        catalog = catalog[:start] + block + catalog[end:]
    return catalog


def main() -> int:
    check = "--check" in sys.argv[1:]
    current = CATALOG.read_text()
    wanted = replace_indexes(current)
    if check:
        if current == wanted:
            print("docs/catalog.md indexes are in sync")
            return 0
        print(
            "docs/catalog.md indexes are STALE — regenerate with:\n"
            "    .venv/bin/python scripts/gen-docs-index.py",
            file=sys.stderr,
        )
        return 1
    if current != wanted:
        CATALOG.write_text(wanted)
        print("docs/catalog.md indexes updated")
    else:
        print("docs/catalog.md indexes already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
